/** Текст сообщения из Discord в простой читаемый вид: без упоминаний, своих эмодзи и разметки. */
export function cleanDiscordText(raw: string): string {
  return raw
    .replace(/<a?:\w+:\d+>/g, '')                 // свои эмодзи сервера
    .replace(/<@[!&]?\d+>/g, '')                  // упоминания людей и ролей
    .replace(/<#\d+>/g, '')                       // упоминания каналов
    .replace(/<t:\d+(?::\w)?>/g, '')              // метки времени
    .replace(/\|\|[^|]*\|\|/g, '')                // спойлеры
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+)\)/g, '$1') // [текст](ссылка) → текст
    .replace(/\*\*([^*]+)\*\*/g, '$1').replace(/__([^_]+)__/g, '$1').replace(/~~([^~]+)~~/g, '$1')
    .replace(/(^|\s)\*([^*\n]+)\*(?=\s|[.,!?]|$)/g, '$1$2')
    .replace(/^#{1,3}\s+/gm, '')                  // заголовки #
    .replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').replace(/[ \t]{2,}/g, ' ')
    .trim();
}
